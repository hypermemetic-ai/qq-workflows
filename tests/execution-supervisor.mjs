import assert from 'node:assert/strict';
import {spawn,spawnSync} from 'node:child_process';
import {mkdirSync,mkdtempSync,writeFileSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createJob,readJob,writeJob,recordCancellation,processFingerprint} from '../workflow/jobs.mjs';
import {readReport} from '../workflow/reports.mjs';
import {runExecutionHost,publishExecutionResult} from '../workflow/execution-host.mjs';
const root=mkdtempSync(join(tmpdir(),'qq-host-proof-'));
const stateDir=join(root,'state');
const owner='coordinator';
const supervisor=pathToFileURL(new URL('../workflow/execution-supervisor.mjs',import.meta.url).pathname).href;
const host=pathToFileURL(new URL('../workflow/execution-host.mjs',import.meta.url).pathname).href;
const pipeline=join(root,'pipeline.mjs');
writeFileSync(pipeline,`let started=0; export const dispatchExecution=async()=>{started=Date.now();return {id:'inner'};}; export const checkExecution=async()=>Date.now()-started<1000?{status:'running',phase:'reviewing'}:{status:'completed',phase:'landed',result:{evidence:'host survived parent'}};`);
createJob({stateDir,id:'survive',role:'execution',workflow:{sessionKey:owner,root},cwd:root});
const driver=join(root,'parent.mjs');
writeFileSync(driver,`import {spawn} from 'node:child_process';import {launchExecutionHost} from ${JSON.stringify(supervisor)};
launchExecutionHost({stateDir:${JSON.stringify(stateDir)},root:${JSON.stringify(root)},jobId:'survive',owner:'coordinator',kind:'open',phaseId:'phase',spawnFn:(bin,args,options)=>spawn(bin,['--input-type=module','-e',\`import {runExecutionHost} from ${JSON.stringify(host)}; await runExecutionHost(\${JSON.stringify(args[1])},{loadPipeline:()=>import(${JSON.stringify(pathToFileURL(pipeline).href)})});\`],options)});setTimeout(()=>process.exit(0),100);`);
const parent=spawnSync(process.execPath,[driver],{encoding:'utf8',timeout:10000});
assert.equal(parent.status,0,parent.stderr);
const deadline=Date.now()+10000;
while(!readJob(stateDir,'survive')?.terminal && Date.now()<deadline)await new Promise(r=>setTimeout(r,50));
const completed=readJob(stateDir,'survive');
assert.equal(completed.status,'completed');
assert.match(readReport(stateDir,completed.terminal.reportId).text,/host survived parent/);
assert.notEqual(completed.process.pid,process.pid);
assert.equal(completed.phase,'landed');
createJob({stateDir,id:'cancel',role:'execution',workflow:{sessionKey:owner,root},cwd:root});
recordCancellation(stateDir,'cancel');
publishExecutionResult({stateDir,jobId:'cancel',result:{ok:true,status:'completed',phase:'landed'}});
assert.equal(readJob(stateDir,'cancel').status,'cancelled','late host outcome cannot overwrite cancellation');
const forged=join(root,'forged.json');
writeFileSync(forged,JSON.stringify({stateDir,root,owner:'other',jobId:'survive',launchId:'forged'}));
await assert.rejects(runExecutionHost(forged),/ownership mismatch/);
console.log('PASS real detached host survives parent exit, durable report precedes terminal, cancellation wins, forged ownership rejected (pipeline is a deterministic test double)');
